inline const char* Find(const char* name) {
    if (!name) return nullptr;
    int lo = 0, hi = kCount - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        const int c = strcasecmp(kEntries[mid].name, name);
        if (c == 0) return kEntries[mid].path;
        if (c < 0) lo = mid + 1; else hi = mid - 1;
    }
    return nullptr;
}
