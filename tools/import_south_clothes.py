"""Import the Lasouth store catalogue without writing to its source directory.

Stable IDs follow catalogue.txt order. Never reorder an existing exported catalogue:
these IDs are persisted by the server. Source files are opened read-only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = [
    ('t-shirts', 'southTop', 'Camisas', 'haut'),
    ('pants', 'southBottom', 'Calças', 'bas'),
    ('boot', 'southShoes', 'Calçados', 'chaussures'),
    ('backpack', 'southBackpack', 'Mochilas', 'sacs'),
    ('mask', 'southMask', 'Máscaras', 'tete'),
    ('ear', 'southEar', 'Brincos', 'bijoux'),
    ('clock', 'southClock', 'Relógios', 'bijoux'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Read-only custom/ directory')
    args = parser.parse_args()
    source = args.source.resolve()
    if source == ROOT or ROOT in source.parents:
        raise ValueError('Source must be outside the destination project')
    raw = (source / 'catalogue.txt').read_bytes()
    rows = [line.split('|') for line in raw.decode().splitlines()]
    out = ROOT / 'app/src/main/assets/clothes/south'
    out.mkdir(parents=True, exist_ok=True)
    groups = []
    hash_file = out / 'source-hashes.json'
    hashes = json.loads(hash_file.read_text()) if hash_file.exists() else {}
    hashes['catalogue.txt'] = hashlib.sha256(raw).hexdigest()
    for model in (7, 9):
        for category, key, label, tab in CATEGORIES:
            items = []
            for row in rows:
                if row[:3] != ['I', str(model), category]:
                    continue
                _, _, _, name, material, texture, apply, remove = row
                relative = Path(texture)
                if relative.is_absolute() or '..' in relative.parts:
                    raise ValueError('Unsafe texture path')
                src = source / 'textures' / relative
                dst = out / relative
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, dst)
                hashes['textures/' + texture] = hashlib.sha256(src.read_bytes()).hexdigest()
                items.append(dict(name=name, material=material, texture=texture,
                                  apply=apply, remove=remove))
            if len(items) > 255:
                raise ValueError('Catalogue does not fit the persisted byte ID')
            groups.append(dict(model=model, key=key, label=label, tab=tab, items=items))
    # Reject a changed export that would silently remap already saved outfits.
    manifest = out / 'catalogue.json'
    if manifest.exists() and json.loads(manifest.read_text(encoding='utf-8')) != groups:
        raise ValueError('Existing catalogue IDs differ; an explicit migration is required')
    manifest.write_text(json.dumps(groups, ensure_ascii=False, indent=2), encoding='utf-8')
    (out / 'catalogue.js').write_text('window.SouthCatalogue = ' + json.dumps(groups, ensure_ascii=False) + ';\n', encoding='utf-8')
    (out / 'source-hashes.json').write_text(json.dumps(hashes, indent=2), encoding='utf-8')
    q = lambda s: json.dumps(s, ensure_ascii=False)
    header = ['#pragma once', '// Generated by tools/import_south_clothes.py. Stable saved IDs.',
              'namespace SouthClothes {',
              'struct Item { const char *name, *material, *texture, *apply, *remove; };',
              'struct Group { int model; const char *key, *label, *tab; const Item* items; int count; };']
    for i, group in enumerate(groups):
        header.append(f'inline const Item items{i}[] = {{')
        for item in group['items']:
            header.append('    {' + ','.join(q(item[k]) for k in ('name', 'material', 'texture', 'apply', 'remove')) + '},')
        header.append('};')
    header.append('inline const Group groups[] = {')
    for i, g in enumerate(groups):
        header.append('    {' + f'{g["model"]},' + ','.join(q(g[k]) for k in ('key', 'label', 'tab')) + f',items{i},{len(g["items"])}' + '},')
    header.extend(['};', '}'])
    for abi in ('samp', 'samp32'):
        (ROOT / f'app/src/main/cpp/{abi}/gui/SouthClothes.h').write_text('\n'.join(header) + '\n', encoding='utf-8')
    print(f'Imported {sum(len(g["items"]) for g in groups)} garments; source hashes recorded.')


if __name__ == '__main__':
    main()
